import { chromium } from 'playwright-core';
const base = process.argv[2] || 'http://localhost:8765/';
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto(base); await p.waitForFunction(() => window.__ready);
await p.click('.tabs button[data-tab="scen"]');
await p.selectOption('#scenSelect', 'repo:donker-strak'); await p.waitForTimeout(2500);
await p.selectOption('#cmpSelect', 'repo:licht-warm');
await p.click('#editPanel summary');
await p.selectOption('#paletteGrid select[data-role="worktop"]', 'terrazzo'); await p.waitForTimeout(2500);
p.on('dialog', d => d.accept('Testvariant'));
await p.click('#scenSaveNew'); await p.waitForTimeout(800);
await p.screenshot({ path: '/workspace/interieur/tmp/ui-scen.png' });
console.log(await p.evaluate(() => ({ list: window.viz.listScenarios().map(s => s.name), ws: window.viz.getPlan().palette.worktop, chip: document.querySelector('#tScenario').textContent })));
await p.click('#cmpSwap'); await p.waitForTimeout(2500);
console.log('after swap', await p.evaluate(() => window.viz.getScenario().name));
console.log(errs.length ? errs : 'no errors');
await b.close();
